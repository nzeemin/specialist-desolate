#!/usr/bin/env python3
"""Convert rooms/room-NN.zx0 (ZX0-packed rooms) into an assembler source.

Usage: python tools/rooms2asm.py [rooms_dir] [out.asm]
Defaults: rooms  desolroom.asm
Emits per-room labels RoomNN, DEFB data, and a RoomTable of DEFW pointers.
"""
import glob
import os
import re
import sys


def main():
    rooms_dir = sys.argv[1] if len(sys.argv) > 1 else 'rooms'
    out_path = sys.argv[2] if len(sys.argv) > 2 else 'desolroom.asm'

    files = {}
    for f in glob.glob(os.path.join(rooms_dir, 'room-*.zx0')):
        m = re.fullmatch(r'room-(\d+)\.zx0', os.path.basename(f))
        if m:
            files[int(m.group(1))] = f
    if not files:
        sys.exit('No room-NN.zx0 files in ' + rooms_dir)
    count = max(files) + 1
    missing = [n for n in range(count) if n not in files]
    if missing:
        sys.exit('Missing rooms: %s' % missing)

    total = 0
    out = ['; Generated by tools/rooms2asm.py from %s/room-NN.zx0 - do not edit' % rooms_dir,
           '; %d rooms, each ZX0-packed (unpack with dzx0)' % count, '']
    for n in range(count):
        data = open(files[n], 'rb').read()
        total += len(data)
        out.append('Room%02d:  ; %d bytes' % (n, len(data)))
        for i in range(0, len(data), 16):
            out.append('  DEFB ' + ','.join('$%02X' % b for b in data[i:i + 16]))
    out += ['RoomsEnd:', '',
            '; Packed room addresses',
            'RoomTable:']
    out += ['  DEFW Room%02d' % n for n in range(count)]
    out += ['', '; Total packed rooms: %d bytes, table: %d bytes' % (total, count * 2), '']
    with open(out_path, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('%d rooms, %d bytes packed + %d bytes table -> %s' % (count, total, count * 2, out_path))


if __name__ == '__main__':
    main()
