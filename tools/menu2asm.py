#!/usr/bin/env python3
"""Convert desolmenu.png (192x128) into desolmenu.asm: ZX0-packed menu image and mask.

Usage: python tools/menu2asm.py [in.png] [out.asm]
Defaults: desolmenu.png  desolmenu.asm

PNG colors: cyan (176,224,230) = transparent (background shows through),
dark pixels = ink, everything else = white.
Both layers are stored like the shadow screen: 128 lines of 24 bytes each, line by
line top to bottom, bit 7 = leftmost pixel. Composite: screen = (background & mask) | image.
  image: 1 = ink on opaque pixel;  mask: 1 = transparent.
Packed with tools/salvador.exe -classic (ZX0), unpack with dzx0.
"""
import os
import subprocess
import sys
import tempfile

import numpy as np
from PIL import Image

W, H = 192, 128
CYAN = (176, 224, 230)


def to_rows(bits):
    out = bytearray()
    for y in range(H):
        for col in range(W // 8):
            v = 0
            for b in bits[y, col * 8:col * 8 + 8]:
                v = (v << 1) | int(b)
            out.append(v)
    return bytes(out)


def pack(data):
    exe = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'salvador.exe')
    with tempfile.TemporaryDirectory() as tmp:
        src, dst = os.path.join(tmp, 'in.bin'), os.path.join(tmp, 'out.zx0')
        open(src, 'wb').write(data)
        subprocess.run([exe, '-classic', '-c', src, dst], check=True, capture_output=True)
        return open(dst, 'rb').read()


def defb(label, comment, data):
    out = ['%s:  ; %s' % (label, comment)]
    for i in range(0, len(data), 16):
        out.append('  DEFB ' + ','.join('$%02X' % b for b in data[i:i + 16]))
    return out


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'desolmenu.png'
    dst = sys.argv[2] if len(sys.argv) > 2 else 'desolmenu.asm'
    img = Image.open(src).convert('RGB')
    if img.size != (W, H):
        sys.exit('%s must be %dx%d, got %dx%d' % (src, W, H, *img.size))
    a = np.array(img).astype(int)
    transparent = np.abs(a - CYAN).sum(axis=2) < 30
    ink = (a.sum(axis=2) < 300) & ~transparent

    image = pack(to_rows(ink))
    mask = pack(to_rows(transparent))
    out = ['; Generated by tools/menu2asm.py from %s - do not edit' % os.path.basename(src),
           '; Menu screen 192x128, ZX0-packed. Composite: (background & mask) | image',
           '; Unpacked size of each layer: %d bytes' % (W // 8 * H), '']
    out += defb('MenuImagePacked', 'image, %d bytes packed' % len(image), image)
    out += ['MenuImagePackedEnd:', '']
    out += defb('MenuMaskPacked', 'mask, %d bytes packed' % len(mask), mask)
    out += ['MenuMaskPackedEnd:', '']
    with open(dst, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('image %d B, mask %d B packed -> %s' % (len(image), len(mask), dst))


if __name__ == '__main__':
    main()
